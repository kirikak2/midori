#!/usr/bin/env ruby
# bundle_plugins.rb -- MIDoRI のプラグイン（/sd/plugins）を 1 つの .mrb にまとめる
#
#   ruby tools/bundle_plugins.rb [プラグインのディレクトリ] [出力]
#   ruby tools/bundle_plugins.rb                       # examples/plugins -> examples/bundle.mrb
#
# lib/*.rb を先に、続けてトップレベルの *.rb を名前順に（"_" で始まるものは除く。
# ローダと同じ）1 つのソースにつなぎ、ファームウェアと同じ mrbc でコンパイルする。
# 各ファイルは lambda で包むので、
#   - トップレベルの return（`return unless $midori_mode == :ui`）はそのファイルだけを抜ける
#   - トップレベルのローカル変数はファイルごと（md などがぶつからない）
# 加えてファイルごとに rescue し、ローダと同じ形で報告して次へ進む。
# class / module / 定数は lambda の中でもトップレベルに定義される。
#
# 出力は bundle.mrb 1 つだけを /sd/plugins/ に置く（元のファイルも置くと二重に読まれる）。
# lib/ のファイルを load するプラグインは、bundle に入っているときは load を飛ばすこと
# （examples/plugins/lumi.rb の `unless Object.const_defined?(:Lumi)`）。

root = File.expand_path("..", __dir__)
dir = File.expand_path(ARGV[0] || File.join(root, "examples/plugins"))
out = File.expand_path(ARGV[1] || File.join(root, "examples/bundle.mrb"))
mrbc = File.join(root, "components/midori-runtime/picoruby/build/mrbc/default/bin/mrbc")
abort "mrbc not found: #{mrbc} (build the firmware once)" unless File.executable?(mrbc)

plugin = ->(path) { !File.basename(path).start_with?("_") }
files = Dir[File.join(dir, "lib", "*.rb")].sort.select(&plugin) +
        Dir[File.join(dir, "*.rb")].sort.select(&plugin)
abort "no plugins in #{dir}" if files.empty?

name = File.basename(out)
src = +"# Generated by tools/bundle_plugins.rb -- do not edit\n"
files.each do |path|
  rel = path.delete_prefix(dir + "/")
  src << "\n# ---- #{rel}\nbegin\n  lambda do\n"
  src << File.read(path).chomp << "\n"
  src << "  end.call\n"
  src << "rescue => e\n"
  src << "  puts \"[Plugin] #{name}: #{rel}: \#{e.message} (\#{e.class})\"\n"
  src << "end\n"
end

rb = out.sub(/\.mrb\z/, "") + ".rb"
File.write(rb, src)
ok = system(mrbc, "-o", out, rb)
abort "mrbc failed (source kept in #{rb})" unless ok
File.delete(rb)
puts "#{out}: #{files.size} files"
files.each { |f| puts "  #{f.delete_prefix(dir + '/')}" }
